"""Generates the default settings: GSettings files and the wallpaper list.

Values come from the tokens where the tokens hold them (wallpaper base
colours, the default accent). The rest are stock GNOME keys that a spec
sets to a stock value, named with the spec row that asks for it.
"""

from xml.sax import saxutils

from apex_desktop.generators import icons
from apex_desktop.kernel import tokens as tokens_lib

Scheme = tokens_lib.Scheme

EXTENSION_UUID = "apex@apex-linux.github.io"
SCHEMA_ID = "io.github.apex_linux.Desktop"
BACKGROUNDS = "/usr/share/backgrounds/apex"

# Installed file name -> design asset name.
WALLPAPERS = {
    "facets-l.svg": "facets-light.svg",
    "facets-d.svg": "facets-dark.svg",
}


def wallpaper_base(tokens: tokens_lib.Tokens, scheme: Scheme) -> str:
    """Returns the base colour `--wall` draws under the wallpaper."""
    return tokens.role("--wall", scheme).split()[0]


def override(tokens: tokens_lib.Tokens) -> str:
    """Returns the vendor GSettings override."""
    light = f"file://{BACKGROUNDS}/facets-l.svg"
    dark = f"file://{BACKGROUNDS}/facets-d.svg"
    return (
        "# Generated by apex_desktop.generators.settings. Do not edit.\n"
        "\n"
        "[org.gnome.desktop.interface]\n"
        f"accent-color='{tokens.default_accent()}'\n"
        f"icon-theme='{icons.THEME}'\n"
        "# Top bar clock draws the weekday (shell-top-bar-and-dock.md).\n"
        "clock-show-weekday=true\n"
        "\n"
        "[org.gnome.desktop.background]\n"
        f"picture-uri='{light}'\n"
        f"picture-uri-dark='{dark}'\n"
        "picture-options='zoom'\n"
        f"primary-color='{wallpaper_base(tokens, Scheme.LIGHT)}'\n"
        "\n"
        "[org.gnome.desktop.screensaver]\n"
        f"picture-uri='{light}'\n"
        "picture-options='zoom'\n"
        f"primary-color='{wallpaper_base(tokens, Scheme.LIGHT)}'\n"
        "\n"
        "[org.gnome.shell]\n"
        f"enabled-extensions=['{EXTENSION_UUID}']\n"
    )


def solid_wallpapers(tokens: tokens_lib.Tokens) -> dict[str, str]:
    """Returns one flat SVG per solid wallpaper, by installed file name.

    They are pictures, not colour-only entries, so the Appearance chooser
    shows them like any other wallpaper (wallpapers-and-app-icons.md).
    """
    return {
        f"{name}.svg": (
            '<svg xmlns="http://www.w3.org/2000/svg" width="2880"'
            ' height="1800" viewBox="0 0 1440 900">\n'
            f'  <rect width="1440" height="900" fill="{value.css()}"/>\n'
            "</svg>\n"
        )
        for name, _, value in tokens.solid_wallpapers()
    }


def schema() -> str:
    """Returns the GSettings schema of the Apex Shell extension."""
    path = "/" + SCHEMA_ID.replace(".", "/") + "/"
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by apex_desktop.generators.settings. Do not edit."
        " -->\n"
        "<schemalist>\n"
        f'  <schema id="{SCHEMA_ID}" path="{path}">\n'
        '    <key name="translucent-surfaces" type="b">\n'
        "      <default>false</default>\n"
        "      <summary>Translucent shell surfaces</summary>\n"
        "      <description>Draw the top bar, dock and shell panels with"
        " their glass tints instead of the solid fallback. Live blur is"
        " not implemented yet (OQ-03).</description>\n"
        "    </key>\n"
        "  </schema>\n"
        "</schemalist>\n"
    )


def background_properties(tokens: tokens_lib.Tokens) -> str:
    """Returns the wallpaper list Settings > Appearance reads."""
    light = saxutils.escape(f"{BACKGROUNDS}/facets-l.svg")
    dark = saxutils.escape(f"{BACKGROUNDS}/facets-d.svg")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!DOCTYPE wallpapers SYSTEM "gnome-wp-list.dtd">\n'
        "<!-- Generated by apex_desktop.generators.settings. Do not edit."
        " -->\n"
        "<wallpapers>\n"
        '  <wallpaper deleted="false">\n'
        "    <name>Facets</name>\n"
        f"    <filename>{light}</filename>\n"
        f"    <filename-dark>{dark}</filename-dark>\n"
        "    <options>zoom</options>\n"
        "    <shade_type>solid</shade_type>\n"
        f"    <pcolor>{wallpaper_base(tokens, Scheme.LIGHT)}</pcolor>\n"
        f"    <scolor>{wallpaper_base(tokens, Scheme.DARK)}</scolor>\n"
        "  </wallpaper>\n"
        + "".join(
            '  <wallpaper deleted="false">\n'
            f"    <name>{saxutils.escape(label)}</name>\n"
            f"    <filename>{BACKGROUNDS}/{name}.svg</filename>\n"
            "    <options>zoom</options>\n"
            "    <shade_type>solid</shade_type>\n"
            f"    <pcolor>{value.css()}</pcolor>\n"
            f"    <scolor>{value.css()}</scolor>\n"
            "  </wallpaper>\n"
            for name, label, value in tokens.solid_wallpapers()
        )
        + "</wallpapers>\n"
    )
