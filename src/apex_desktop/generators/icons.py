"""Builds the Apex icon theme's masters and its index.theme.

Masters are the stroked drawings exactly as the contact sheets draw them.
GTK and St recolour symbolic icons by forcing `fill`, so the shipped files
are those masters with every stroke turned into a filled outline; that
step needs a geometry library and runs at development time
(entrypoints/build_icons.py). This module is standard library only.
"""

from collections.abc import Sequence
from typing import Any

from apex_desktop.kernel import tokens as tokens_lib

THEME = "Apex"
SYMBOLIC_DIR = "symbolic"

# Apex -> Adwaita -> hicolor: undrawn symbolic names fall back to Adwaita,
# app icons to each app's own hicolor icon. Colloid's full-colour icons
# would be merged into this theme (option C in apex-symbolic.md); they are
# withheld until OQ-16 is settled.
INHERITS = ("Adwaita", "hicolor")

# Adwaita's full-colour files for names Apex draws, linked into this theme
# so GTK 4 finds them before the Apex glyph (entrypoints/list_full_colour).
FULL_COLOUR_LIST = "icons/adwaita-full-colour.txt"
FULL_COLOUR_SIZES = ("scalable", "16x16")
FULL_COLOUR_HEADER = (
    "# Generated by apex_desktop.entrypoints.list_full_colour from\n"
    "# adwaita-icon-theme. Do not edit. One path under\n"
    "# /usr/share/icons/Adwaita per line; Apex links each into its own tree.\n"
)
ADWAITA = "/usr/share/icons/Adwaita"
_CONTEXTS = {
    "apps": "Applications",
    "devices": "Devices",
    "emblems": "Emblems",
    "mimetypes": "MimeTypes",
    "places": "Places",
    "status": "Status",
}


def master(entry: dict[str, Any], tokens: tokens_lib.Tokens) -> str:
    """Returns the stroked master SVG of one glyph table entry.

    Layer order follows the sheets: `o` (inactive, at the inactive
    opacity), then `d` (stroked), then `f` (solid, even-odd).
    """
    icon = tokens.icon()
    stroke = (
        f'fill="none" stroke="#000" stroke-width="{icon["stroke"]["default"]}"'
        f' stroke-linecap="{icon["lineCap"]}"'
        f' stroke-linejoin="{icon["lineJoin"]}"'
    )
    layers = []
    if entry["o"]:
        layers.append(
            f'<path d="{entry["o"]}" {stroke}'
            f' stroke-opacity="{icon["inactiveOpacity"]}"/>'
        )
    if entry["d"]:
        layers.append(f'<path d="{entry["d"]}" {stroke}/>')
    if entry["f"]:
        layers.append(
            f'<path d="{entry["f"]}" fill="#000" fill-rule="evenodd"/>'
        )
    body = "".join(f"  {layer}\n" for layer in layers)
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16"'
        ' width="16" height="16">\n'
        f"{body}</svg>\n"
    )


def drawings(glyphs: dict[str, dict[str, Any]]) -> dict[str, list[str]]:
    """Groups names by drawing.

    Returns:
        The first name of each drawing, in sorted order, mapped to the other
        names that share it; those ship as symlinks.
    """
    canonical: dict[tuple[str, str, str], str] = {}
    groups: dict[str, list[str]] = {}
    for name in sorted(glyphs):
        entry = glyphs[name]
        key = (entry["d"], entry["f"], entry["o"])
        if key in canonical:
            groups[canonical[key]].append(name)
        else:
            canonical[key] = name
            groups[name] = []
    return groups


def read_full_colour(text: str) -> list[str]:
    """Returns the paths in a full-colour list, without comments."""
    return [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not line.startswith("#")
    ]


def index_theme(full_colour: Sequence[str] = ()) -> str:
    """Returns the theme's index.theme.

    Args:
        full_colour: Adwaita-relative paths the theme links to; their
            directories are declared with Adwaita's sizes.
    """
    directories = sorted({path.rsplit("/", 1)[0] for path in full_colour})
    sections = [
        f"[{SYMBOLIC_DIR}]\n"
        "Context=Status\n"
        "Size=16\n"
        "MinSize=8\n"
        "MaxSize=512\n"
        "Type=Scalable\n"
    ]
    for directory in directories:
        size, context = directory.split("/")
        if size == "scalable":
            metrics = "Size=128\nMinSize=8\nMaxSize=512\nType=Scalable\n"
        else:
            metrics = f"Size={size.split('x')[0]}\nType=Fixed\n"
        sections.append(
            f"[{directory}]\nContext={_CONTEXTS.get(context, 'Status')}\n"
            + metrics
        )
    return (
        "# Generated by apex_desktop.generators.icons. Do not edit.\n"
        "[Icon Theme]\n"
        f"Name={THEME}\n"
        "Comment=Apex Symbolic\n"
        f"Inherits={','.join(INHERITS)}\n"
        "Hidden=false\n"
        f"Directories={','.join([SYMBOLIC_DIR, *directories])}\n"
        "\n" + "\n".join(sections)
    )


def requires(full_colour: Sequence[str]) -> str:
    """Returns requires.txt: the RPM and paths the full-colour links need."""
    return (
        "# Generated by apex_desktop.generators.icons. Do not edit.\n"
        "# What the image must carry for apex-desktop: one Fedora RPM per\n"
        "# line, then a path it installs that the build tests for.\n"
        "#\n"
        "# <rpm> <path>\n"
        "\n"
        "# Full-colour icons the Apex theme links to.\n"
        + "".join(
            f"adwaita-icon-theme {ADWAITA}/{path}\n" for path in full_colour
        )
    )
