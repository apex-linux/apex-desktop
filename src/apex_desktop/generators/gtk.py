"""Generates the libadwaita style sheet from the design tokens.

libadwaita has no theme API, but it reads its colours from CSS variables
(libadwaita 1.6 and later), so one style sheet can set them for both
schemes with a `prefers-color-scheme` media query (GTK 4.16 and later).

How the sheet reaches apps is open (OQ-18): the legacy decision keeps
libadwaita's colours and changes only the window radius. So the file is
installed but nothing loads it yet; see README.md.
"""

from apex_desktop.kernel import tokens as tokens_lib

Scheme = tokens_lib.Scheme

# libadwaita variable -> Apex colour role, per system/README.md "Mapping to
# GNOME".
_COLORS = (
    ("--window-bg-color", "--win"),
    ("--window-fg-color", "--fg"),
    ("--view-bg-color", "--view"),
    ("--view-fg-color", "--fg"),
    ("--headerbar-bg-color", "--head"),
    ("--headerbar-fg-color", "--fg"),
    ("--sidebar-bg-color", "--side"),
    ("--sidebar-fg-color", "--fg"),
    ("--card-bg-color", "--card"),
    ("--card-fg-color", "--fg"),
    ("--popover-bg-color", "--pop"),
    ("--popover-fg-color", "--fg"),
    ("--dialog-bg-color", "--win"),
    ("--dialog-fg-color", "--fg"),
    ("--border-color", "--border"),
    ("--error-color", "--err"),
    ("--warning-color", "--warn"),
    ("--success-color", "--ok"),
)


def _variables(tokens: tokens_lib.Tokens, scheme: Scheme) -> str:
    lines = [
        f"  {variable}: {tokens.color(role, scheme).css()};\n"
        for variable, role in _COLORS
    ]
    # Secondary text is the foreground at an alpha, which is what
    # libadwaita's dim opacity expresses.
    dim = tokens.color("--dim", scheme).alpha
    lines.append(f"  --dim-opacity: {round(dim * 100)}%;\n")
    lines.append(f"  --window-radius: {tokens.radius('window')};\n")
    return "".join(lines)


def stylesheet(tokens: tokens_lib.Tokens) -> str:
    """Returns the libadwaita style sheet for both colour schemes."""
    features = tokens.font_features().replace("'", '"')
    return (
        "/* Generated by apex_desktop.generators.gtk from"
        " design/system/tokens.json. Do not edit. */\n\n"
        f":root {{\n{_variables(tokens, Scheme.LIGHT)}}}\n\n"
        "@media (prefers-color-scheme: dark) {\n"
        f"  :root {{\n"
        + "".join(
            f"  {line}"
            for line in _variables(tokens, Scheme.DARK).splitlines(True)
        )
        + "  }\n}\n\n"
        f"window {{\n  font-feature-settings: {features};\n}}\n"
    )
